export function getUntrOperationalData(presetId?: string): OperationalData {
  switch (presetId) {
    case '9m-2024-vs-2023':
      return UNTR_OPERATIONAL_9M2024_VS_2023;
    case '1h-2024-vs-2023':
      return UNTR_OPERATIONAL_1H2024_VS_2023;
    case 'q1-2024-vs-2023':
      return UNTR_OPERATIONAL_Q12024_VS_2023;
    case 'fy-2023-vs-2022':
      return UNTR_OPERATIONAL_FY2023_VS_2022;
    case 'fy-2024-vs-2023':
    default:
      return UNTR_OPERATIONAL_FY2024_VS_2023;
  }
}

export function getUntrOperationalDataForPeriodPair(
  p1Label: string,
  p2Label: string
): OperationalData {
  const p1Clean = p1Label.trim().toLowerCase();
  const p2Clean = p2Label.trim().toLowerCase();

  // Match standard pairs
  if (
    (p1Clean.includes('2023') && p2Clean.includes('2024') && p1Clean.includes('9m')) ||
    (p1Clean.includes('9m 2023') && p2Clean.includes('9m 2024'))
  ) {
    return UNTR_OPERATIONAL_9M2024_VS_2023;
  }
  if (
    (p1Clean.includes('2023') && p2Clean.includes('2024') && p1Clean.includes('1h')) ||
    (p1Clean.includes('1h 2023') && p2Clean.includes('1h 2024'))
  ) {
    return UNTR_OPERATIONAL_1H2024_VS_2023;
  }
  if (
    (p1Clean.includes('2023') && p2Clean.includes('2024') && p1Clean.includes('q1')) ||
    (p1Clean.includes('q1 2023') && p2Clean.includes('q1 2024'))
  ) {
    return UNTR_OPERATIONAL_Q12024_VS_2023;
  }
  if (
    (p1Clean.includes('2022') && p2Clean.includes('2023')) ||
    (p1Clean.includes('fy 2022') && p2Clean.includes('fy 2023'))
  ) {
    return UNTR_OPERATIONAL_FY2023_VS_2022;
  }

  // Default: FY 2024 vs FY 2023
  return UNTR_OPERATIONAL_FY2024_VS_2023;
}
